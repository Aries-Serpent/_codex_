class TestVerifyPackageWithSigstoreNoAttestation:
    """Behaviour when sigstore is installed but the package has no attestation."""

    def _make_pypi_response(self, *, with_provenance: bool = False) -> bytes:
        release_file: dict = {"filename": "requests-2.31.0-py3-none-any.whl"}
        if with_provenance:
            release_file["provenance"] = "https://pypi.org/fake/bundle.json"
        payload = {"urls": [release_file]}
        return json.dumps(payload).encode()

    def test_no_attestation_returns_unverified(self) -> None:
        """When PyPI returns no provenance field, result is 'unverified'."""
        mock_resp = MagicMock()
        mock_resp.read.return_value = self._make_pypi_response(with_provenance=False)
        mock_resp.__enter__ = lambda s: s
        mock_resp.__exit__ = MagicMock(return_value=False)

        with (
            patch.object(sv, "_SIGSTORE_AVAILABLE", True),
            patch("urllib.request.urlopen", return_value=mock_resp),
        ):
            result = sv._verify_with_sigstore("requests", "2.31.0")

        assert result.status == "unverified", "Result must not be empty"
        assert "no sigstore attestation" in result.detail.lower(), "Result must not be empty"

    def test_network_error_returns_error_status(self) -> None:
        """Network failures produce status='error', not an uncaught exception."""
        import urllib.error

        with (
            patch.object(sv, "_SIGSTORE_AVAILABLE", True),
            patch(
                "urllib.request.urlopen",
                side_effect=urllib.error.HTTPError(
                    url="", code=404, msg="Not Found", hdrs=None, fp=None  # type: ignore[arg-type]
                ),
            ),
        ):
            result = sv._verify_with_sigstore("cryptography", "41.0.3")

        assert result.status == "error", "Result must not be empty"
        assert "404" in result.detail, "Result must not be empty"


