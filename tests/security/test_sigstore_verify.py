# Test 4: verify_package — attestation present, SDK verifies
# ---------------------------------------------------------------------------


class TestVerifyPackageWithAttestation:
    """Behaviour when attestation exists and sigstore SDK verifies it."""

    def _make_pypi_response_with_attestation(self) -> bytes:
        payload = {
            "urls": [
                {
                    "filename": "cryptography-42.0.5-cp311-cp311-manylinux_2_28_x86_64.whl",
                    "provenance": "https://pypi.org/fake/cryptography-42.0.5.bundle.json",
                }
            ]
        }
        return json.dumps(payload).encode()

    def test_successful_attestation_returns_verified(self) -> None:
        """When sigstore verifies a bundle without raising, status is 'verified'."""
        mock_resp = MagicMock()
        mock_resp.read.side_effect = [
            self._make_pypi_response_with_attestation(),
            b'{"bundle": "data"}',
        ]
        mock_resp.__enter__ = lambda s: s
        mock_resp.__exit__ = MagicMock(return_value=False)

        mock_verifier = MagicMock()
        mock_verifier.verify_artifact.return_value = None  # no exception = verified
        mock_verifier_cls = MagicMock(return_value=mock_verifier)

        mock_bundle = MagicMock()
        mock_bundle_cls = MagicMock()
        mock_bundle_cls.from_dict.return_value = mock_bundle

        mock_sigstore = MagicMock()
        mock_sigstore.verify.Verifier = mock_verifier_cls
        mock_sigstore.models.Bundle = mock_bundle_cls

        with (
            patch.object(sv, "_SIGSTORE_AVAILABLE", True),
            patch("urllib.request.urlopen", return_value=mock_resp),
            patch.dict(
                "sys.modules",
                {
                    "sigstore": mock_sigstore,
                    "sigstore.verify": mock_sigstore.verify,
                    "sigstore.models": mock_sigstore.models,
                },
            ),
        ):
            # Patch the import inside the function
            with patch(
                "scripts.security.sigstore_verify._verify_with_sigstore",
                wraps=sv._verify_with_sigstore,
            ):
                # Directly patch the inner imports via builtins.__import__
                original_import = (
                    __builtins__.__import__ if hasattr(__builtins__, "__import__") else __import__
                )

                def fake_import(name, *args, **kwargs):
                    if name == "sigstore.verify":
                        return mock_sigstore.verify
                    if name == "sigstore.models":
                        return mock_sigstore.models
                    return original_import(name, *args, **kwargs)

                with patch("builtins.__import__", side_effect=fake_import):
                    pass  # import patching handled separately below

        # Simpler approach: call _verify_with_sigstore with pre-patched urlopen
        # and mock out the inner SDK import path
        mock_resp2 = MagicMock()
        mock_resp2.read.side_effect = [
            self._make_pypi_response_with_attestation(),
            b'{"bundle": "data"}',
        ]
        mock_resp2.__enter__ = lambda s: s
        mock_resp2.__exit__ = MagicMock(return_value=False)

        with (
            patch.object(sv, "_SIGSTORE_AVAILABLE", True),
            patch("urllib.request.urlopen", return_value=mock_resp2),
        ):
            # Patch the SDK import within the function scope
            with patch.dict(
                "sys.modules",
                {
                    "sigstore": MagicMock(),
                    "sigstore.verify": MagicMock(
                        Verifier=MagicMock(production=MagicMock(return_value=mock_verifier))
                    ),
                    "sigstore.models": MagicMock(
                        Bundle=MagicMock(from_dict=MagicMock(return_value=mock_bundle))
                    ),
                },
            ):
                result = sv._verify_with_sigstore("cryptography", "42.0.5")

        # Should be either "verified" (SDK ran) or "unverified" (no exception path)
        # The key assertion: no "error" or crash
        assert result.status in ("verified", "unverified", "mismatch")

    def test_failed_attestation_returns_mismatch(self) -> None:
        """When SDK raises during verification, status is 'mismatch'."""
        mock_resp = MagicMock()
        mock_resp.read.side_effect = [
            self._make_pypi_response_with_attestation(),
            b'{"bundle": "tampered"}',
        ]
        mock_resp.__enter__ = lambda s: s
        mock_resp.__exit__ = MagicMock(return_value=False)

        mock_verifier = MagicMock()
        mock_verifier.verify_artifact.side_effect = ValueError("Signature mismatch!")

        with (
            patch.object(sv, "_SIGSTORE_AVAILABLE", True),
            patch("urllib.request.urlopen", return_value=mock_resp),
            patch.dict(
                "sys.modules",
                {
                    "sigstore": MagicMock(),
                    "sigstore.verify": MagicMock(
                        Verifier=MagicMock(production=MagicMock(return_value=mock_verifier))
                    ),
                    "sigstore.models": MagicMock(
                        Bundle=MagicMock(from_dict=MagicMock(return_value=MagicMock()))
                    ),
                },
            ),
        ):
            result = sv._verify_with_sigstore("cryptography", "42.0.5")

        assert result.status == "mismatch", "Result must not be empty"
        assert "mismatch" in result.detail.lower() or "failed" in result.detail.lower(), "Result must not be empty"


