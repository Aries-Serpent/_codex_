"""
Test Audit Meta In Report

Test module for audit meta in report.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest


def _run(args: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )


@pytest.mark.smoke
def test_meta_propagates_and_renders(tmp_path):
    """
    Verifies S3→S4 meta propagation and report rendering:
    - Ensures capabilities_scored.json carries 'meta' when present in raw.
    - Renders report and checks for 'Meta' section for a capability with meta.
    """
    runner = Path("scripts/space_traversal/audit_runner.py")
    if not runner.exists():
        pytest.skip("audit runner missing")

    # Optional deps for S6 template
    if importlib.util.find_spec("jinja2") is None or importlib.util.find_spec("yaml") is None:
        pytest.skip("pyyaml/jinja2 not installed in test env")

    # Ensure audit_artifacts directory exists
    artifacts = Path("audit_artifacts")
    artifacts.mkdir(parents=True, exist_ok=True)

    # Run S1..S3
    for stage in ("S1", "S2", "S3"):
        cp = _run([str(runner), "stage", stage])
        assert cp.returncode == 0, f"{stage} failed: {cp.stderr}"

    # S3 outputs capabilities.json (not capabilities_raw.json)
    raw_path = artifacts / "capabilities.json"
    if not raw_path.exists():
        pytest.skip("capabilities.json not created by S3")

    # Inject meta into one capability (emulating a dynamic detector that adds meta)
    data = json.loads(raw_path.read_text(encoding="utf-8"))
    if not data.get("capabilities"):
        pytest.skip("no capabilities to annotate")
    data["capabilities"][0]["meta"] = {"layer": "test-meta", "owner": "qa"}
    raw_path.write_text(json.dumps(data, indent=2), encoding="utf-8")

    # S4..S6
    for stage in ("S4", "S5", "S6"):
        cp = _run([str(runner), "stage", stage])
        assert cp.returncode == 0, f"{stage} failed: {cp.stderr}"

    # Check scored JSON carries the injected meta
    scored = json.loads((artifacts / "capabilities_scored.json").read_text(encoding="utf-8"))
    cap0 = scored["capabilities"][0]
    assert "meta" in cap0 and cap0["meta"].get("layer") == "test-meta", "Condition must be true"

    # Check S6 report.md contains 'Meta:' for that capability
    report_path = artifacts / "report.md"
    if not report_path.exists():
        pytest.skip("report.md not generated by S6")
    text = report_path.read_text(encoding="utf-8")
    assert "Meta:" in text and "layer: test-meta" in text, "Condition must be true"
